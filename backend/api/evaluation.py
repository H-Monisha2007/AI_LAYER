"""
Evaluation & Benchmarks API Endpoint

Returns actual computed research evaluation metrics:
- Overall accuracy, precision, recall, F1-score, ROC-AUC, PR-AUC, EER
- Confusion matrix
- Per-generator accuracy breakdown
- Unseen-generator generalization test results
- Robustness evaluation under JPEG quality degradation & noise
- Failure analysis report (FP & FN classification)

Rule: All metrics originate strictly from actual evaluation calculations.
Zero hardcoded or fabricated numbers.
"""
import os
import json
from typing import Dict, Any
from fastapi import APIRouter

router = APIRouter()

WEIGHTS_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "model_weights"))
DATASET_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "datasets"))


@router.get("/evaluation")
async def get_evaluation_metrics() -> Dict[str, Any]:
    """
    Returns live evaluation results generated by model evaluation runs.
    """
    eval_report_path = os.path.join(WEIGHTS_DIR, "evaluation_report.json")
    training_report_path = os.path.join(WEIGHTS_DIR, "training_report.json")
    manifest_path = os.path.join(DATASET_DIR, "dataset_manifest.json")

    manifest_data = {}
    if os.path.exists(manifest_path):
        try:
            with open(manifest_path, "r") as f:
                manifest_data = json.load(f)
        except Exception:
            manifest_data = {}

    # Check if computed evaluation report exists
    if os.path.exists(eval_report_path):
        try:
            with open(eval_report_path, "r") as f:
                eval_data = json.load(f)
            eval_data["dataset_summary"] = manifest_data.get("summary", {})
            return eval_data
        except Exception:
            pass

    # Check if training report exists
    has_weights = os.path.exists(training_report_path)
    report_data = {}
    if has_weights:
        try:
            with open(training_report_path, "r") as f:
                report_data = json.load(f)
        except Exception:
            has_weights = False

    rgb_metrics = report_data.get("models", {}).get("rgb_spatial", {}).get("metrics", {})
    freq_metrics = report_data.get("models", {}).get("frequency_dct", {}).get("metrics", {})
    noise_metrics = report_data.get("models", {}).get("noise_residual", {}).get("metrics", {})

    return {
        "status": "ready" if has_weights else "MODEL_NOT_READY",
        "has_trained_weights": has_weights,
        "overall_metrics": {
            "accuracy": rgb_metrics.get("accuracy") if has_weights else None,
            "precision": rgb_metrics.get("precision") if has_weights else None,
            "recall": rgb_metrics.get("recall") if has_weights else None,
            "f1_score": rgb_metrics.get("f1_score") if has_weights else None,
            "roc_auc": rgb_metrics.get("roc_auc") if has_weights else None,
            "eer": rgb_metrics.get("eer") if has_weights else None,
        },
        "domain_metrics": {
            "rgb_spatial": rgb_metrics if has_weights else "MODEL_NOT_READY",
            "frequency_dct": freq_metrics if has_weights else "MODEL_NOT_READY",
            "noise_residual": noise_metrics if has_weights else "MODEL_NOT_READY",
        },
        "confusion_matrix": rgb_metrics.get("confusion_matrix") if has_weights else None,
        "per_generator_performance": [],
        "unseen_generator_test": {
            "target_generators": ["Midjourney v5/v6", "FLUX.1"],
            "accuracy": None,
            "f1_score": None,
            "roc_auc": None,
            "note": "Evaluates generalization capabilities on unseen generative architectures."
        },
        "robustness_benchmarks": {
            "original": rgb_metrics.get("accuracy") if has_weights else None,
            "jpeg_95": None,
            "jpeg_75": None,
            "jpeg_50": None,
            "resize_50": None,
            "gaussian_blur": None,
            "gaussian_noise": None,
        },
        "dataset_summary": manifest_data.get("summary", {})
    }
